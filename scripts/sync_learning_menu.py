#!/usr/bin/env python3
"""Generate the learning-menu metadata from docs/*.md.

The generated module is used by the SPA routes, the learning sidebar, and the
NotebookLM guide. Run this after changing docs; Dockerfile runs it too so a
push always deploys the exact document set bundled in the image.
"""
from __future__ import annotations

import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS_DIR = ROOT / "docs"
INDEX_HTML = ROOT / "app" / "frontend" / "index.html"
OUT_MODULE = ROOT / "app" / "frontend" / "js" / "data" / "learnDocs.js"


def sort_key(path: Path) -> tuple[int, int | str]:
    return (0, int(path.stem)) if path.stem.isdigit() else (1, path.stem.casefold())


def title_for(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.match(r"^#\s+(.+?)\s*$", line)
        if match:
            return re.sub(r"^(?:Day|DAY)\s+\d+\s*[—-]\s*", "", match.group(1)).strip()
    return path.stem


def menu_html(docs: list[dict[str, str]]) -> str:
    rows = []
    for doc in docs:
        icon = "fa-spell-check" if doc["id"] == "voca" else "fa-circle-dot"
        rows.append(
            f'            <a class="nav-item" data-view="learn-{html.escape(doc["id"])}">'
            f'<i class="fa-solid {icon}"></i>{html.escape(doc["label"])}</a>'
        )
    return "\n".join(rows)


def main() -> None:
    files = sorted(DOCS_DIR.glob("*.md"), key=sort_key)
    docs = []
    for path in files:
        doc_id = path.stem
        title = title_for(path)
        label = "핵심 용어집" if doc_id == "voca" else f"Day {int(doc_id)} · {title}"
        docs.append({"id": doc_id, "file": path.name, "title": title, "label": label})

    OUT_MODULE.write_text(
        "// Generated by scripts/sync_learning_menu.py from docs/*.md. Do not edit manually.\n"
        f"export const LEARN_DOCS = {json.dumps(docs, ensure_ascii=False, indent=2)};\n",
        encoding="utf-8",
    )

    source = INDEX_HTML.read_text(encoding="utf-8")
    replacement = '<div class="nav-children" id="nav-learn">\n' + menu_html(docs) + "\n          </div>"
    updated, count = re.subn(
        r'<div class="nav-children" id="nav-learn">.*?</div>',
        replacement,
        source,
        count=1,
        flags=re.S,
    )
    if count != 1:
        raise SystemExit("index.html에서 학습 메뉴를 찾지 못했습니다.")
    INDEX_HTML.write_text(updated, encoding="utf-8")
    print(f"학습 메뉴 동기화 완료: {len(docs)}개 문서")


if __name__ == "__main__":
    main()
